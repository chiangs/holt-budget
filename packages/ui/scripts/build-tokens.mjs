// Turns design/design-system/tokens.json into CSS custom properties.
// Output: packages/ui/src/tokens.css. Run with `pnpm tokens`.
//
// - Colour and shadow tokens can differ per theme. Each theme gets a
//   [data-theme="…"] block; hearth-light is also the :root default.
// - A value written as "{accent}" refers to another token and becomes var(--accent).
// - Spacing, radius, size and blur tokens go on :root.
// - Type styles become .type-<name> classes plus --font-ui and --font-data.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const source = resolve(root, "design/design-system/tokens.json");
const target = resolve(here, "../src/tokens.css");

const tokens = JSON.parse(readFileSync(source, "utf8"));
const themes = tokens.color.themes.map((t) => t.id);
const defaultTheme = "hearth-light";

const ref = (value) =>
  typeof value === "string" ? value.replace(/^\{([\w-]+)\}$/, "var(--$1)") : String(value);

/** Collect per-theme declarations from a token list whose values may be per-theme maps. */
function perTheme(list, into) {
  for (const token of list) {
    const { name, value } = token;
    for (const theme of themes) {
      const v = value !== null && typeof value === "object" ? value[theme] : value;
      if (v === undefined) continue;
      (into[theme] ??= []).push(`  --${name}: ${ref(v)};`);
    }
  }
}

const themed = {};
perTheme(tokens.color.tokens, themed);
perTheme(tokens.shadow.tokens, themed);

const shared = [];
for (const group of ["spacing", "radius", "size", "blur"]) {
  for (const { name, value } of tokens[group].tokens) shared.push(`  --${name}: ${ref(value)};`);
}
shared.push(`  --font-ui: ${tokens.type.families.ui};`);
shared.push(`  --font-data: ${tokens.type.families.data};`);

const typeClasses = [];
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    const decl = [
      `font-family: var(--font-${group.family})`,
      `font-size: ${style.fontSize}`,
      `line-height: ${style.lineHeight}`,
      `font-weight: ${style.fontWeight}`,
    ];
    if (style.letterSpacing) decl.push(`letter-spacing: ${style.letterSpacing}`);
    if (group.family === "data") decl.push("font-variant-numeric: tabular-nums");
    typeClasses.push(`.type-${style.name} { ${decl.join("; ")}; }`);
  }
}

const out = [
  "/* Generated by packages/ui/scripts/build-tokens.mjs from design/design-system/tokens.json. Do not edit. */",
  "",
  ":root {",
  ...shared,
  ...(themed[defaultTheme] ?? []),
  "}",
  "",
  ...themes.flatMap((theme) => [`[data-theme="${theme}"] {`, ...(themed[theme] ?? []), "}", ""]),
  ...typeClasses,
  "",
].join("\n");

writeFileSync(target, out);
console.log(`Wrote ${target} (${themes.length} themes).`);
